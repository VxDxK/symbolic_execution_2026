const generatedTestMarker = "// Code generated by symbolic-execution-course; DO NOT EDIT."

func GenerateTestFile(sourceFile string) string {
	sourceFile, err := filepath.Abs(sourceFile)
	if err != nil {
		panic(fmt.Errorf("generate tests: %w", err))
	}
	source, err := os.ReadFile(sourceFile)
	if err != nil {
		panic(fmt.Errorf("generate tests: %w", err))
	}
	file, err := parser.ParseFile(token.NewFileSet(), sourceFile, source, 0)
	if err != nil {
		panic(fmt.Errorf("generate tests: %w", err))
	}
	target := strings.TrimSuffix(sourceFile, filepath.Ext(sourceFile)) + "_test.go"
	if strings.HasSuffix(sourceFile, "_test.go") {
		panic("generate tests: input must not be a test file")
	}
	existing, err := os.ReadFile(target)
	if err == nil && !bytes.HasPrefix(existing, []byte(generatedTestMarker+"\n")) {
		panic("generate tests: refusing to overwrite manual tests: " + target)
	}
	if err != nil && !os.IsNotExist(err) {
		panic(fmt.Errorf("generate tests: %w", err))
	}
	var body strings.Builder
	usesMath := false
	for _, declaration := range file.Decls {
		fn, ok := declaration.(*ast.FuncDecl)
		if !ok {
			continue
		}
		if fn.Recv != nil || fn.Type.TypeParams != nil {
			panic("generate tests: methods and generics are unsupported: " + fn.Name.Name)
		}
		if fn.Name.Name == "init" || fn.Body == nil {
			continue
		}
		text, needsMath := generateFunctionTests(string(source), fn.Name.Name)
		body.WriteString(text)
		usesMath = usesMath || needsMath
	}
	var output strings.Builder
	fmt.Fprintf(&output, "%s\npackage %s\n", generatedTestMarker, file.Name.Name)
	if body.Len() > 0 {
		output.WriteString("import (\n\"testing\"\n")
		if usesMath {
			output.WriteString("\"math\"\n")
		}
		output.WriteString(")\n")
	}
	output.WriteString(body.String())
	formatted, err := format.Source([]byte(output.String()))
	if err != nil {
		panic(fmt.Errorf("generate tests: format %s: %w", target, err))
	}
	temporary, err := os.CreateTemp(filepath.Dir(target), ".generated-tests-*")
	if err != nil {
		panic(fmt.Errorf("generate tests: %w", err))
	}
	defer os.Remove(temporary.Name())
	if _, err := temporary.Write(formatted); err != nil {
		temporary.Close()
		panic(err)
	}
	if err := temporary.Close(); err != nil {
		panic(err)
	}
	if err := os.Chmod(temporary.Name(), 0644); err != nil {
		panic(err)
	}
	if err := os.Rename(temporary.Name(), target); err != nil {
		panic(err)
	}
	return target
}

func generateFunctionTests(source, name string) (text string, usesMath bool) {
	defer func() {
		if failure := recover(); failure != nil {
			panic(fmt.Sprintf("generate tests for %s: %v", name, failure))
		}
	}()
	states := Analyse(source, name)
	var body strings.Builder
	fmt.Fprintf(&body, "func TestGenerated_%s(t *testing.T) {\n", name)
	cases, limited := 0, 0
	for _, state := range states {
		if state.Status == LimitReached {
			limited++
			continue
		}
		if state.Status != Returned && state.Status != Panicked {
			panic("unexpected execution status")
		}
		translator := state.Analyser.Z3Translator
		ctx := translator.GetContext().(*z3.Context)
		solver := z3.NewSolver(ctx)
		solver.Assert(state.pathFormula)
		sat, err := solver.Check()
		if err != nil {
			panic(err)
		}
		if !sat {
			continue
		}
		model := solver.Model()
		frame := state.frame()
		arguments := make([]string, len(frame.Function.Params))
		for i, param := range frame.Function.Params {
			expression := symbolic.NewSymbolicVariable(param.Name(), expressionType(param.Type()))
			value, err := translator.TranslateExpression(expression)
			if err != nil {
				panic(err)
			}
			literal, floating := modelLiteral(model, value.(z3.Value), expression.Type())
			usesMath = usesMath || floating
			typ := types.TypeString(param.Type(), func(p *types.Package) string {
				if p == frame.Function.Pkg.Pkg {
					return ""
				}
				return p.Name()
			})
			arguments[i] = fmt.Sprintf("%s(%s)", typ, literal)
		}
		fmt.Fprintf(&body, "t.Run(\"path_%d\", func(t *testing.T) {\n", cases)
		call := fmt.Sprintf("%s(%s)", name, strings.Join(arguments, ", "))
		if state.Status == Panicked {
			body.WriteString("completed := false\ndefer func() { value := recover(); if completed { t.Fatal(\"expected panic\") }; _ = value }()\n")
			body.WriteString(call + "\ncompleted = true\n")
		} else {
			names := make([]string, len(frame.ReturnValues))
			for i := range names {
				names[i] = fmt.Sprintf("got%d", i)
			}
			if len(names) > 0 {
				fmt.Fprintf(&body, "%s := %s\n", strings.Join(names, ", "), call)
			} else {
				body.WriteString(call + "\n")
			}
			for i, expression := range frame.ReturnValues {
				value, err := translator.TranslateExpression(expression)
				if err != nil {
					panic(err)
				}
				expected, floating := modelLiteral(model, value.(z3.Value), expression.Type())
				usesMath = usesMath || floating
				if floating {
					if model.Eval(value.(z3.Float).IsNaN(), true).(z3.Bool).String() == "true" {
						fmt.Fprintf(&body, "if !math.IsNaN(float64(got%d)) { t.Fatalf(\"result %d: expected NaN, got %%v\", got%d) }\n", i, i, i)
					} else {
						fmt.Fprintf(&body, "if math.Float64bits(float64(got%d)) != math.Float64bits(%s) { t.Fatalf(\"result %d: expected %%v, got %%v\", %s, got%d) }\n", i, expected, i, expected, i)
					}
				} else {
					resultType := types.TypeString(frame.Function.Signature.Results().At(i).Type(), func(p *types.Package) string {
						if p == frame.Function.Pkg.Pkg {
							return ""
						}
						return p.Name()
					})
					expected = resultType + "(" + expected + ")"
					fmt.Fprintf(&body, "if got%d != %s { t.Fatalf(\"result %d: expected %%v, got %%v\", %s, got%d) }\n", i, expected, i, expected, i)
				}
			}
		}
		body.WriteString("})\n")
		cases++
	}
	if cases == 0 {
		panic("no completed execution paths")
	}
	if limited > 0 {
		fmt.Fprintf(&body, "// Skipped %d paths that reached the analysis limit.\n", limited)
	}
	body.WriteString("}\n")
	return body.String(), usesMath
}

func modelLiteral(model *z3.Model, value z3.Value, typ symbolic.ExpressionType) (string, bool) {
	if typ == symbolic.Float64Type {
		float := value.(z3.Float)
		if model.Eval(float.IsNaN(), true).(z3.Bool).String() == "true" {
			return "math.NaN()", true
		}
		bits := model.Eval(float.ToIEEEBV(), true).(z3.BV)
		number, literal := bits.AsBigUnsigned()
		if !literal {
			panic("non-concrete float model")
		}
		return fmt.Sprintf("math.Float64frombits(0x%x)", number), true
	}
	evaluated := model.Eval(value, true)
	if typ == symbolic.BoolType {
		boolean, literal := evaluated.(z3.Bool).AsBool()
		if !literal {
			panic("non-concrete boolean model")
		}
		return fmt.Sprintf("%t", boolean), false
	}
	number, literal := evaluated.(z3.BV).AsBigUnsigned()
	if typ.IsSigned() {
		number, literal = evaluated.(z3.BV).AsBigSigned()
	}
	if !literal {
		panic("non-concrete integer model")
	}
	return typ.String() + "(" + number.String() + ")", false
}
